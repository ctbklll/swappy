const EN_NOTIF_BODIES: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^(.+) ต้องการเป็นเพื่อนกับคุณ$/, (m) => `${m[1]} wants to be your friend`],
  [/^(.+) ตอบรับคำขอเป็นเพื่อนของคุณแล้ว$/, (m) => `${m[1]} accepted your friend request`],
  [/^(.+) ขอแลกเวรวันที่ (\S+)$/, (m) => `${m[1]} requests to swap shifts on ${m[2]}`],
  [/^(.+) ขอยกให้เวรวันที่ (\S+)$/, (m) => `${m[1]} wants to give you their shift on ${m[2]}`],
  [/^(.+) ยกเลิกคำขอแลกเวร$/, (m) => `${m[1]} cancelled the swap request`],
  [/^(.+) ปฏิเสธคำขอแลกเวร$/, (m) => `${m[1]} declined your swap request`],
  [/^(.+) ตอบรับการแลกเวรแล้ว$/, (m) => `${m[1]} accepted the swap`],
];

const fill = (s: string, vars?: Record<string, string | number>) =>
  vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : s;

export function translate(lang: Lang, th: string, vars?: Record<string, string | number>) {
  return fill(lang === "en" ? (EN[th] ?? th) : th, vars);
}

export function translateServer(lang: Lang, th: string) {
  return lang === "en" ? (EN_SERVER[th] ?? EN[th] ?? th) : th;
}

export function translateNotification(lang: Lang, n: { title: string; body: string }) {
  if (lang !== "en") return { title: n.title, body: n.body };
  let body = n.body;
  for (const [re, f] of EN_NOTIF_BODIES) {
    const m = n.body.match(re);
    if (m) { body = f(m); break; }
  }
  return { title: EN_NOTIF_TITLES[n.title] ?? n.title, body };
}

